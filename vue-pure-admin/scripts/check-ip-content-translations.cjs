const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(require('node:path').join(__dirname,'../src/utils/ipContentTranslation.ts'),'utf8');
const moduleCode = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const api = {};
vm.runInNewContext(moduleCode,{exports:api,JSON,Object,Number,String});
const row = {id:12,summary:'新品发布',contact:'张三',profile:'{"cooperationTips":"Retain original notes"}',brief:{externalIPs:[{reason:'保留原始文本'}]},translation:{state:'completed',values:{en:{summary:'Product launch','brief.externalIPs.0.reason':'Original entry'},zh:{'profile.cooperationTips':'保留原始备注'}}}};
const before = JSON.stringify(row);
const english = api.translatedIPRecord(row,'en');
assert.equal(english.summary,'Product launch');
assert.equal(english.brief.externalIPs[0].reason,'Original entry');
assert.equal(english.contact,'张三');
assert.equal(api.translatedIPRecord(row,'zh').profile.cooperationTips,'保留原始备注');
assert.equal(api.translatedIPRecord(row,'en',true),row);
assert.equal(JSON.stringify(row),before,'read projections must not modify editing/saving sources');
const draft = {id:12,summary:'An unsaved reviewer edit'};
api.applyIPTranslationUpdates([draft],'ip_request',[{id:12,type:'ip_request',translation:row.translation}]);
assert.equal(draft.summary,'An unsaved reviewer edit','polling must not reset unsaved review fields');
assert.equal(draft.translation,row.translation);
const other = {id:12};
api.applyIPTranslationUpdates([other],'ip_resource',[{id:12,type:'ip_request',translation:row.translation}]);
assert.equal(other.translation,undefined,'same numeric IDs from different entities must not mix');
const malicious = {id:1,translation:{values:{en:{'__proto__.polluted':'bad','constructor.prototype.polluted':'bad','translation.state':'bad'}}}};
api.translatedIPRecord(malicious,'en');
assert.equal({}.polluted,undefined);
console.log('PASS: bilingual projections, original preservation, nested/JSON fields, draft-safe status updates and entity isolation');
