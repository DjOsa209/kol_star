export function fieldLabel(label: string): string {
  const locale = i18n.global.locale as string | { value: string };
  const localeCode = typeof locale === "string" ? locale : locale.value;
  return localeCode === "en" ? (englishFieldLabels[label] ?? label) : label;
}
